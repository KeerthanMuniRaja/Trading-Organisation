import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const principal=JSON.parse(process.env.PRINCIPALS_JSON??'[]').find(p=>p.role==='researcher');
if(!principal)throw new Error('A scoped researcher principal is required');
const localPython=join(root,'integrations','skfolio','.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python');
const python=process.env.PYTHON_BIN??(existsSync(localPython)?localPython:(process.platform==='win32'?'python':'python3'));
const env=Object.fromEntries(['PATH','Path','SystemRoot','SYSTEMROOT','WINDIR','TEMP','TMP'].filter(k=>process.env[k]).map(k=>[k,process.env[k]]));
Object.assign(env,{API_URL:process.env.API_URL??'http://127.0.0.1:3000',API_TOKEN:principal.token,PYTHONIOENCODING:'utf-8',PYTHONNOUSERSITE:'1'});
for(const name of ['HERMES_ENABLED','HERMES_ENGINE','HERMES_SOURCE_PATH','HERMES_PYTHON','HERMES_MODEL','HERMES_MODEL_BASE_URL','HERMES_MODEL_API_KEY','HERMES_TIMEOUT_SECONDS'])if(process.env[name])env[name]=process.env[name];
const child=spawn(python,['integrations/hermes/development_worker.py',...process.argv.slice(2)],{cwd:root,env,windowsHide:true,stdio:'inherit',shell:false});
child.once('error',()=>{console.error('Development worker could not start');process.exitCode=1;});
child.once('exit',code=>{process.exitCode=code??1;});
for(const signal of ['SIGINT','SIGTERM'])process.once(signal,()=>child.kill(signal));
